// Generates src/styles/tokens.css from design-system/tokens.json, and
// copies design-system/bundle.css to src/styles/yada.css unchanged.
//
// Run with: node scripts/gen-tokens.mjs

import { readFileSync, writeFileSync, copyFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, "..");

const tokensJsonPath = join(repoRoot, "design-system", "tokens.json");
const bundleCssPath = join(repoRoot, "design-system", "bundle.css");
const tokensCssPath = join(repoRoot, "src", "styles", "tokens.css");
const yadaCssPath = join(repoRoot, "src", "styles", "yada.css");

const tokens = JSON.parse(readFileSync(tokensJsonPath, "utf8"));

// Families that carry a flat `tokens: [{ name, value, usage }]` array.
const families = ["color", "spacing", "radius", "shadow"];

const lines = [];
for (const family of families) {
  const entries = tokens[family]?.tokens;
  if (!entries) continue;
  for (const { name, value, usage } of entries) {
    if (usage) {
      lines.push(`  /* ${usage} */`);
    }
    lines.push(`  --${name}: ${value};`);
  }
}

const css = `/* Generated by scripts/gen-tokens.mjs from design-system/tokens.json. */\n/* Do not edit by hand — rerun the script instead. */\n:root {\n${lines.join(
  "\n"
)}\n}\n`;

mkdirSync(dirname(tokensCssPath), { recursive: true });
writeFileSync(tokensCssPath, css, "utf8");

mkdirSync(dirname(yadaCssPath), { recursive: true });
copyFileSync(bundleCssPath, yadaCssPath);

console.log(`Wrote ${tokensCssPath}`);
console.log(`Copied ${bundleCssPath} -> ${yadaCssPath}`);
